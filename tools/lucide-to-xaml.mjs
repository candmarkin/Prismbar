// Converts Lucide SVG icons into a WPF ResourceDictionary of Geometry resources.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import svgpath from "svgpath";

const here = path.dirname(fileURLToPath(import.meta.url));
const iconsDir = path.join(here, "node_modules", "lucide-static", "icons");
const pkg = JSON.parse(fs.readFileSync(path.join(here, "node_modules", "lucide-static", "package.json"), "utf8"));
const out = path.join(here, "..", "src", "Prismbar", "Resources", "Icons.xaml");

const names = ["volume-2", "volume-1", "volume", "volume-x", "mic", "mic-off", "wifi", "wifi-low", "wifi-off", "cable",
  "battery-full", "battery-medium", "battery-low", "battery-warning", "battery-charging", "calendar", "clock", "search",
  "play", "pause", "skip-forward", "skip-back", "download", "trash-2", "sticky-note", "list-checks", "timer", "hourglass",
  "cpu", "memory-stick", "github", "settings", "chevron-up", "sun", "moon", "cloud-sun", "cloud", "cloud-fog",
  "cloud-drizzle", "cloud-rain", "cloud-snow", "cloud-lightning", "x", "bell", "music", "folder", "globe", "app-window",
  "plus", "refresh-cw", "external-link", "grip"];

const attr = (el, n) => { const m = new RegExp(`\\s${n}="([^"]*)"`).exec(el); return m ? parseFloat(m[1]) : 0; };
const sattr = (el, n) => { const m = new RegExp(`\\s${n}="([^"]*)"`).exec(el); return m ? m[1] : ""; };
const pts = s => s.trim().split(/[\s,]+/).map(Number);

function toPath(tag, el) {
  switch (tag) {
    case "path": return sattr(el, "d");
    case "line": return `M${attr(el, "x1")} ${attr(el, "y1")} L${attr(el, "x2")} ${attr(el, "y2")}`;
    case "polyline":
    case "polygon": {
      const p = pts(sattr(el, "points")); let d = `M${p[0]} ${p[1]}`;
      for (let i = 2; i < p.length; i += 2) d += ` L${p[i]} ${p[i + 1]}`;
      return tag === "polygon" ? d + " Z" : d;
    }
    case "circle":
    case "ellipse": {
      const cx = attr(el, "cx"), cy = attr(el, "cy");
      const rx = tag === "circle" ? attr(el, "r") : attr(el, "rx"), ry = tag === "circle" ? rx : attr(el, "ry");
      return `M${cx - rx} ${cy} A${rx} ${ry} 0 1 0 ${cx + rx} ${cy} A${rx} ${ry} 0 1 0 ${cx - rx} ${cy} Z`;
    }
    case "rect": {
      const x = attr(el, "x"), y = attr(el, "y"), w = attr(el, "width"), h = attr(el, "height");
      let rx = attr(el, "rx") || attr(el, "ry");
      if (!rx) return `M${x} ${y} H${x + w} V${y + h} H${x} Z`;
      rx = Math.min(rx, w / 2, h / 2);
      return `M${x + rx} ${y} H${x + w - rx} A${rx} ${rx} 0 0 1 ${x + w} ${y + rx} V${y + h - rx} A${rx} ${rx} 0 0 1 ${x + w - rx} ${y + h} H${x + rx} A${rx} ${rx} 0 0 1 ${x} ${y + h - rx} V${y + rx} A${rx} ${rx} 0 0 1 ${x + rx} ${y} Z`;
    }
  }
  return "";
}

let missing = [];
let body = "";
for (const requested of names) {
  let name = requested;
  let file = path.join(iconsDir, `${name}.svg`);
  if (!fs.existsSync(file) && name === "github") { name = "git-pull-request"; file = path.join(iconsDir, `${name}.svg`); }
  if (!fs.existsSync(file)) { missing.push(requested); continue; }
  const svg = fs.readFileSync(file, "utf8");
  const parts = [];
  for (const m of svg.matchAll(/<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*)\/?>/g)) {
    const d = toPath(m[1], " " + m[2]);
    if (d) parts.push(svgpath(d).abs().unshort().unarc().round(3).toString());
  }
  body += `    <Geometry x:Key="Icon.${requested}">${parts.join(" ")}</Geometry>\n`;
}
if (missing.length) { console.error("Missing Lucide icons: " + missing.join(", ")); process.exit(1); }

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `<!-- Generated by tools/lucide-to-xaml.mjs from lucide-static ${pkg.version} (ISC). Do not edit. -->
<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
${body}</ResourceDictionary>
`);
console.log(`Wrote ${names.length} icons to ${out}`);
